function 计算风格(等级, 分配) {
    const L = Math.min(160, Math.max(1, Number(等级) || 1))
    const cap = 等级 * 8
    const maxV = 800

    const items = [
        {k: '血', v: Math.max(0, (Number(分配?.体质) || L) - L), i: 0},
        {k: '精', v: Math.max(0, (Number(分配?.智力) || L) - L), i: 1},
        {k: '攻', v: Math.max(0, (Number(分配?.力量) || L) - L), i: 2},
        {k: '速', v: Math.max(0, (Number(分配?.敏捷) || L) - L), i: 3},
    ]
    items.sort((x, y) => {
        if (y.v !== x.v) return y.v - x.v
        return x.i - y.i
    })
    const e1 = items[0].v
    const e2 = items[1].v
    if (e1 > 0 && e2 === 0) {
        const 单型 = {血: '气血型', 精: '精力型', 攻: '攻击型', 速: '速度型'}
        return 单型[items[0].k]
    }
    return items[0].k + items[1].k + '型'
}

function 修正属性分配(等级, 分配) {
    const L = Math.min(160, Math.max(1, Number(等级) || 1))
    const cap = 8 * L
    const d = {体质: L, 智力: L, 力量: L, 敏捷: L}
    const maxV = 800

    let 体 = Number(分配?.体质)
    let 智 = Number(分配?.智力)
    let 力 = Number(分配?.力量)
    let 敏 = Number(分配?.敏捷)

    if (![体, 智, 力, 敏].every((x) => Number.isFinite(x))) {
        return {...d}
    }
    if (体 < L) 体 = L
    if (智 < L) 智 = L
    if (力 < L) 力 = L
    if (敏 < L) 敏 = L
    体 = Math.min(maxV, 体)
    智 = Math.min(maxV, 智)
    力 = Math.min(maxV, 力)
    敏 = Math.min(maxV, 敏)
    if (体 + 智 + 力 + 敏 > cap) {
        return {...d}
    }
    return {体质: 体, 智力: 智, 力量: 力, 敏捷: 敏}
}

function 解析装备格(部位, 格) {
    const out = {}
    if (!格 || typeof 格 !== 'object') return out
    const 名称 = 格.名称
    if (名称 === 主将装备无) return out
    const 词条 = 格.词条

    if (部位 === '头盔' && 名称 && 头盔配置[名称]) {
        const cfg = 头盔配置[名称]
        const key = 词条 && cfg.词条.includes(词条) ? 词条 : cfg.词条[0]
        out[key] = cfg.数值
        return out
    }
    if (部位 === '项饰' && 名称 === '缀星项链') {
        out.精力 = 3200
        return out
    }
    if (部位 === '武器' && 名称 && 武器表[名称]) {
        Object.assign(out, 武器表[名称])
        return out
    }
    if (部位 === '护腕' && 名称 === '星链护腕') {
        out.气血 = 3200
        return out
    }
    if (部位 === '铠甲' && 名称 && 铠甲表[名称]) {
        Object.assign(out, 铠甲表[名称])
        return out
    }
    if (部位 === '战靴' && 名称 === '龙骨靴') {
        if (词条 === '敏捷') out.敏捷 = 100
        else out.速度 = 100
    }
    return out
}

function 解析装备格汇总(部位, 格) {
    if (格 && typeof 格 === 'object' && 格.名称 === 主将装备无) return {}
    const out = {...解析装备格(部位, 格)}
    if (!格 || !Array.isArray(格.宝石)) return out

    const allowed = new Set(主将装备宝石属性按部位[部位] || [])
    for (const g of 格.宝石) {
        if (!g || typeof g !== 'object' || !g.属性) continue
        if (allowed.size > 0 && !allowed.has(g.属性)) continue

        const min = g.数值 || 15
        const max = g.数值 || 15
        const step = 1
        const raw = Number(g.数值)
        const base = Number.isFinite(raw) ? raw : max
        const snapped = min + Math.round((base - min) / step) * step
        const val = Math.min(max, Math.max(min, snapped))
        const attr = g.属性
        out[attr] = (Number(out[attr]) || 0) + val
    }
    return out
}

