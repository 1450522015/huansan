function 主将前世槽攻血连乘系数(职业经历) {
    let 攻击 = 1
    let 气血 = 1
    const arr = Array.isArray(职业经历) ? 职业经历 : []
    for (let i = 0; i < 3; i++) {
        const raw = arr[i]
        if (raw == null || String(raw).trim() === '') continue
        const 轴 = 分类转职业轴(raw)
        if (轴 === '武') 攻击 *= 1.1
        else if (轴 === '文') 气血 *= 1.1
    }
    return {攻击, 气血}
}

