function 等级系数(等级) {
    const L = Math.min(160, Math.max(1, Math.trunc(Number(等级) || 1)))
    const k = Math.floor((L - 1) / 5)
    const L0 = 1 + k * 5
    const c0 = 20 + k * 4
    return c0 + (L - L0)
}

