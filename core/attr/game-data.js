function 副将默契战斗加成(默契度, 战斗职业轴 = '武') {
    const 轴 = 战斗职业轴 === '文' || 战斗职业轴 === '异' ? 战斗职业轴 : '武'
    const cap = 500000
    const split = 200000
    const span2 = 300000
    const v = Math.min(cap, Math.max(0, Math.trunc(Number(默契度)) || 0))

    function lin(seg1Max, seg2End) {
        if (v <= split) return (v / split) * seg1Max
        return seg1Max + ((v - split) / span2) * (seg2End - seg1Max)
    }

    const 命中 = Math.round(lin(15, 25))
    const 暴击 = Math.round(lin(10, 15))
    const 反击 = Math.round(lin(10, 15))
    const 致命 = Math.round(lin(5, 10))
    const 躲避上限 = 轴 === '文' ? 20 : 10
    const 躲避 = Math.round(lin(10, 躲避上限))

    const out = {命中率: 命中, 暴击率: 暴击, 反击率: 反击, 致命率: 致命, 躲避率: 躲避}

    if (轴 === '武') {
        out.连击率 = Math.round(lin(6, 15))
    } else if (轴 === '文') {
        out.反震率 = Math.round(lin(2, 5))
    } else {
        out.法爆率 = Math.round(lin(15, 25))
        out.爆伤力 = Math.round(lin(10, 15))
    }

    return out
}

