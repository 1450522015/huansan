function 分段天赋值(等级, 段列表) {
    const L = Math.min(160, Math.max(1, Number(等级) || 1))
    for (const [from, to, v0, v1] of 段列表) {
        if (L >= from && L <= to) {
            if (to === from) return v0
            const t = (L - from) / (to - from)
            return v0 + (v1 - v0) * t
        }
    }
    return 段列表.length ? 段列表[段列表.length - 1][3] : 0
}

function 天赋百分比(名称, 等级) {
    const seg = 天赋段[名称]
    if (!seg) return 0
    return 分段天赋值(等级, seg)
}

