/**
 * 计算单个天赋的百分比值（单位 %）
 * @param {string} 名称
 * @param {number} 等级
 * @returns {number} 百分比值，例如 160 级强攻返回 50
 */
export function 获取天赋值(名称, 等级) {
    const seg = 天赋分段表[名称]
    if (!seg) return 0

    const L = Math.min(160, Math.max(1, Number(等级) || 1))
    for (const [from, to, v0, v1] of seg) {
        if (L >= from && L <= to) {
            if (to === from) return v0
            const t = (L - from) / (to - from)
            return v0 + (v1 - v0) * t
        }
    }
    return seg.length ? seg[seg.length - 1][3] : 0
}

/**
 * 收集全部天赋效果（只显示武将实际拥有的天赋，值为百分比）
 * @param {Array} 天赋列表
 * @returns {Record<string, number>}
 */
export function 收集天赋效果(天赋列表) {
    const out = {}
    if (!Array.isArray(天赋列表)) return out

    for (const t of 天赋列表) {
        if (!t || typeof t !== 'object' || !t.名称) continue
        const val = 获取天赋值(t.名称, Number(t.等级) || 1)
        if (val) {
            out[t.名称] = Math.round(val * 100) / 100
        }
    }
    return out
}

/**
 * 计算天赋乘系数（强攻、强血）
 * @param {Array} 天赋列表
 * @returns {{ 攻: number, 血: number }}
 */
export function 收集天赋乘系数(天赋列表) {
    let 攻 = 1
    let 血 = 1

    if (!Array.isArray(天赋列表)) return {攻, 血}

    for (const t of 天赋列表) {
        if (!t || typeof t !== 'object' || !t.名称) continue
        const p = 获取天赋值(t.名称, Number(t.等级) || 1)
        if (!p) continue
        if (t.名称 === '强攻') 攻 *= 1 + p / 100
        if (t.名称 === '强血') 血 *= 1 + p / 100
    }

    return {攻, 血}
}

/**
 * 计算天赋加法部分（暴击力、法爆率等属性加成）
 * @param {Array} 天赋列表
 * @returns {Object}
 */
export function 计算天赋加法(天赋列表) {
    const acc = {}
    if (!Array.isArray(天赋列表)) return acc

    for (const t of 天赋列表) {
        if (!t || typeof t !== 'object' || !t.名称) continue
        const name = t.名称
        const val = 获取天赋值(name, Number(t.等级) || 1)
        if (!val) continue

        if (name === '暴击') acc.暴击力 = (acc.暴击力 || 0) + val
        if (name === '法爆') acc.法爆率 = (acc.法爆率 || 0) + val
        if (name === '爆率') acc.暴击率 = (acc.暴击率 || 0) + val
        if (name === '反击') acc.反击率 = (acc.反击率 || 0) + val
        if (name === '躲避') acc.躲避率 = (acc.躲避率 || 0) + val
        if (name === '致命') acc.致命率 = (acc.致命率 || 0) + val
    }

    return acc
}
