export function 处理舍命一击(战局, 回合信息, 出招方玩家状态, 出招方下标, 接招方玩家状态, 接招方下标) {
    const 出招状态 = 获取武将状态(出招方玩家状态, 出招方下标)
    if (!出招状态 || 出招状态.气血 <= 0) return

    const 出招方玩家 = 获取玩家信息(战局, 出招方玩家状态)
    const 出招方属性 = 获取武将属性(出招方玩家, 出招方下标)
    const 出招方名称 = 获取武将名称(出招方玩家, 出招方下标)

    const 技能效果 = 出招方属性.技能效果['舍命一击']
    if (!技能效果) return

    const 面板伤害 = 技能效果.当前效果
    const 气血消耗 = 技能效果.气血消耗
    const 精力消耗 = 技能效果.精力消耗

    let 实际气血消耗 = 气血消耗
    if (气血消耗 >= 出招状态.气血) {
        if (出招状态.气血 > 1000) {
            实际气血消耗 = 出招状态.气血 - 1
        } else {
            return
        }
    }

    if (精力消耗 > 出招状态.精力) {
        return
    }

    出招状态.气血 -= 实际气血消耗
    出招状态.精力 -= 精力消耗

    let 实际目标下标 = 接招方下标
    let 接招状态 = 获取武将状态(接招方玩家状态, 实际目标下标)

    if (!接招状态 || 接招状态.气血 <= 0) {
        实际目标下标 = 获取最高速存活武将下标(接招方玩家状态)
        接招状态 = 获取武将状态(接招方玩家状态, 实际目标下标)
    }

    if (!接招状态 || 接招状态.气血 <= 0) return

    const 接招方玩家 = 获取玩家信息(战局, 接招方玩家状态)
    const 接招方属性 = 获取武将属性(接招方玩家, 实际目标下标)
    const 接招方名称 = 获取武将名称(接招方玩家, 实际目标下标)
    const 接招方抗物理 = 获取武将抗物理(接招方玩家, 实际目标下标)

    const 对方真实物理抗性 = Math.min(100, Math.max(0, 接招方抗物理))
    const 对方有效物理抗性 = Math.min(100, Math.max(0, 对方真实物理抗性 - 出招方属性.穿透率))
    let 最终伤害 = Math.round(面板伤害 * (1 - 对方有效物理抗性 / 100))
    if (最终伤害 < 1) 最终伤害 = 1

    受到伤害(战局, 接招方玩家状态, 实际目标下标, '舍命一击', 最终伤害)

    回合信息.战况事件序列.push({
        玩家名: 出招方玩家.用户名,
        武将下标: 出招方下标,
        动画名称: '舍命一击',
        横幅显示: `舍命一击`,
        目标: [{
            玩家名: 接招方玩家.用户名,
            武将下标: 实际目标下标,
            气血伤害: 最终伤害,
            新状态: {
                气血: 接招状态.气血,
                buff: 收集武将buff(接招方玩家状态, 实际目标下标),
            },
        }],
        气血伤害: 实际气血消耗,
        新状态: {气血: 出招状态.气血, 精力: 出招状态.精力},
        简要文本: `${出招方名称} 舍命一击 ${接招方名称} 受到${最终伤害}点伤害`,
    })

    if (概率判断(接招方属性.反震率)) {
        受到伤害(战局, 出招方玩家状态, 出招方下标, '反震', 最终伤害)
        回合信息.战况事件序列.push({
            玩家名: 接招方玩家.用户名,
            武将下标: 实际目标下标,
            动画名称: '反震',
            横幅显示: `${接招方名称}反震`,
            目标: [{
                玩家名: 出招方玩家.用户名,
                武将下标: 出招方下标,
                气血伤害: 最终伤害,
                新状态: {
                    气血: 出招状态.气血,
                },
            }],
            简要文本: `${接招方名称} 反震攻击 ${出招方名称} 伤害值${最终伤害}`,
        })
    }
}

