/**
 * 概率判断（独立随机事件）
 */
function 概率判断(概率值) {
    return Math.random() * 100 < 概率值
}

/**
 * 获取天赋值（百分比）
 */
function 获取天赋值(武将属性, 天赋名称) {
    return 武将属性.天赋效果?.[天赋名称] || 0
}

/**
 * 获取武将名称
 */
function 获取武将名称(玩家信息, 武将下标) {
    if (武将下标 === -1) return 玩家信息.用户名
    return 玩家信息.配置.副将列表[武将下标].人物
}

/**
 * 收集武将状态中的buff名称（去重）
 */
function 收集武将buff(玩家状态, 武将下标) {
    const 武将状态 = 获取武将状态(玩家状态, 武将下标)
    if (!武将状态 || !武将状态.buff) return []
    const buff集合 = new Set()
    for (const buff of 武将状态.buff) {
        if (buff.名称) {
            buff集合.add(buff.名称)
        }
    }
    return Array.from(buff集合)
}

/**
 * 获取最高速存活武将下标
 */
function 获取最高速存活武将下标(玩家状态, 包含死亡主将 = false) {
    let 最高速武将 = null
    let 最高速排名 = Infinity

    const 主将 = 玩家状态.主将
    if (主将 && 主将.速度排名 < 最高速排名) {
        if (包含死亡主将 || 主将.气血 > 0) {
            最高速武将 = 主将
            最高速排名 = 主将.速度排名
        }
    }

    for (const 副将 of 玩家状态.副将列表) {
        if (副将 && 副将.气血 > 0 && 副将.速度排名 < 最高速排名) {
            最高速武将 = 副将
            最高速排名 = 副将.速度排名
        }
    }

    return 最高速武将 ? 最高速武将.武将下标 : -1
}

function 获取存活武将列表(玩家状态) {
    const 结果 = []
    const 主将 = 玩家状态.主将
    if (主将 && 主将.气血 > 0) {
        结果.push(主将)
    }
    for (const 副将 of 玩家状态.副将列表) {
        if (副将 && 副将.气血 > 0) {
            结果.push(副将)
        }
    }
    return 结果
}

/**
 * 获取多目标武将列表（含主目标切换逻辑）
 */
function 获取多目标武将列表(玩家状态, 接招方下标, 目标数量) {
    let 实际主目标下标 = 接招方下标
    let 接招状态 = 获取武将状态(玩家状态, 实际主目标下标)

    if (!接招状态 || 接招状态.气血 <= 0) {
        实际主目标下标 = 获取最高速存活武将下标(玩家状态)
        接招状态 = 获取武将状态(玩家状态, 实际主目标下标)
    }

    if (!接招状态 || 接招状态.气血 <= 0) return []

    const 存活武将 = 获取存活武将列表(玩家状态)
    存活武将.sort((a, b) => a.速度排名 - b.速度排名)

    const 目标武将列表 = [接招状态]
    for (const 武将 of 存活武将) {
        if (目标武将列表.length >= 目标数量) break
        if (武将.武将下标 === 实际主目标下标) continue
        目标武将列表.push(武将)
    }

    return 目标武将列表
}

/**
 * 获取所有存活武将列表
 */
function 获取所有存活武将列表(战局) {
    let 红方武将列表 = 获取存活武将列表(战局.红方.状态)
    let 黑方武将列表 = 获取存活武将列表(战局.黑方.状态)
    return [...红方武将列表, ...黑方武将列表]
}

/**
 * 处理武将死亡（从副将列表中移除，加入死亡列表）
 */
function 处理武将死亡(战局) {
    for (const 玩家状态 of [战局.红方.状态, 战局.黑方.状态]) {
        if (玩家状态.主将 && 玩家状态.主将.气血 <= 0) {
            玩家状态.主将.buff = []
        }
        for (let i = 玩家状态.副将列表.length - 1; i >= 0; i--) {
            const 副将 = 玩家状态.副将列表[i]
            if (副将 && 副将.气血 <= 0) {
                玩家状态.副将列表[i] = null
                if (!玩家状态.副将死亡列表) {
                    玩家状态.副将死亡列表 = []
                }
                玩家状态.副将死亡列表.push(副将.武将下标)
            }
        }
    }
}

/**
 * 检查武将是否拥有指定名称的buff
 */
function 检查武将拥有buff(玩家状态, 武将下标, buff名称) {
    const 武将状态 = 获取武将状态(玩家状态, 武将下标)
    if (!武将状态 || !武将状态.buff) return false
    return 武将状态.buff.some(b => b.名称 === buff名称)
}

/**
 * 移除武将身上的指定名称buff
 */
function 移除武将buff(玩家状态, 武将下标, buff名称) {
    const 武将状态 = 获取武将状态(玩家状态, 武将下标)
    if (!武将状态 || !武将状态.buff) return false
    const 原有buff = 武将状态.buff.find(b => b.名称 === buff名称)
    if (!原有buff) return false
    武将状态.buff = 武将状态.buff.filter(b => b.名称 !== buff名称)
    return true
}

function 受到伤害(战局, 玩家状态, 武将下标, 伤害类型, 伤害值) {
    const 武将状态 = 获取武将状态(玩家状态, 武将下标)
    武将状态.气血 = Math.max(0, 武将状态.气血 - 伤害值)
    移除武将buff(玩家状态, 武将下标, '围')
    if (武将状态.气血 <= 0) {
        return 处理武将死亡(战局)
    }
}

function 重新计算速度排名(战局) {
    const 红方状态 = 战局.红方.状态
    const 黑方状态 = 战局.黑方.状态

    const 所有武将 = []

    所有武将.push(红方状态.主将)
    for (const 副将 of 红方状态.副将列表) {
        if (副将) 所有武将.push(副将)
    }

    所有武将.push(黑方状态.主将)
    for (const 副将 of 黑方状态.副将列表) {
        if (副将) 所有武将.push(副将)
    }

    所有武将.sort((a, b) => {
        const a玩家 = 获取玩家信息(战局, a)
        const b玩家 = 获取玩家信息(战局, b)
        const a速度 = 获取武将速度(a玩家, a.武将下标)
        const b速度 = 获取武将速度(b玩家, b.武将下标)
        const 差值 = a速度 - b速度
        if (差值 > 20) return -1
        if (差值 < -20) return 1
        const 概率 = (差值 + 20) / 40
        return Math.random() < 概率 ? -1 : 1
    })

    所有武将.forEach((武将, 索引) => {
        武将.速度排名 = 索引 + 1
    })
}

