import {
    获取武将状态,
    获取玩家信息,
    获取武将属性,
    获取武将攻击,
    获取武将防御,
    获取武将抗物理,
    获取武将最大气血,
    获取武将名称,
    获取天赋值,
    获取最高速存活武将下标,
    受到伤害,
    概率判断,
    收集武将buff,
} from "./common.js";

/**
 * 攻击伤害浮动（0.9 ~ 1.1 闭区间）
 */
function 攻击伤害浮动() {
    return Math.floor(90 + Math.random() * 21) / 100
}

/**
 * 获取合击伙伴属性和名称（从己方队伍中随机选一个非自己单位）
 * 如果没有其他存活队友，返回攻击方自己
 */
function 获取合击伙伴属性(战局, 攻击方玩家状态, 攻击方下标) {
    const 攻击方玩家 = 获取玩家信息(战局, 攻击方玩家状态)
    const 可用武将 = []

    if (攻击方下标 !== -1 && 攻击方玩家状态.主将.气血 > 0) {
        可用武将.push({
            属性: 获取武将属性(攻击方玩家, -1),
            攻击: 获取武将攻击(攻击方玩家, -1),
            名称: 获取武将名称(攻击方玩家, -1)
        })
    }

    for (const 副将 of 攻击方玩家状态.副将列表) {
        if (副将 && 副将.气血 > 0 && 副将.武将下标 !== 攻击方下标) {
            可用武将.push({
                属性: 获取武将属性(攻击方玩家, 副将.武将下标),
                攻击: 获取武将攻击(攻击方玩家, 副将.武将下标),
                名称: 获取武将名称(攻击方玩家, 副将.武将下标)
            })
        }
    }

    if (可用武将.length > 0) {
        return 可用武将[Math.floor(Math.random() * 可用武将.length)]
    }

    return {
        属性: 获取武将属性(攻击方玩家, 攻击方下标),
        攻击: 获取武将攻击(攻击方玩家, 攻击方下标),
        名称: 获取武将名称(攻击方玩家, 攻击方下标)
    }
}

/**
 * 执行单次攻击
 * @param {object} 战局 - 整个战局对象
 * @param {object} 回合信息 - 当前回合信息
 * @param {object} 攻击方玩家状态 - 攻击方的玩家状态
 * @param {number} 攻击方下标 - 武将下标
 * @param {object} 防守方玩家状态 - 防守方的玩家状态
 * @param {number} 防守方下标 - 武将下标
 * @param {number} 连击次数 - 当前是第几次攻击（从1开始）
 * @returns {boolean} 是否命中
 */
function 执行攻击(战局, 回合信息, 攻击方玩家状态, 攻击方下标, 防守方玩家状态, 防守方下标, 连击次数) {
    const 攻击方状态 = 获取武将状态(攻击方玩家状态, 攻击方下标)
    const 攻击方玩家 = 获取玩家信息(战局, 攻击方玩家状态)
    const 攻击方属性 = 获取武将属性(攻击方玩家, 攻击方下标)
    const 攻击方攻击 = 获取武将攻击(攻击方玩家, 攻击方下标)
    const 攻击方防御 = 获取武将防御(攻击方玩家, 攻击方下标)
    const 攻击方抗物理 = 获取武将抗物理(攻击方玩家, 攻击方下标)

    let 实际防守方下标 = 防守方下标
    const 原防守方状态 = 获取武将状态(防守方玩家状态, 防守方下标)
    if (!原防守方状态 || 原防守方状态.气血 <= 0) {
        实际防守方下标 = 获取最高速存活武将下标(防守方玩家状态)
    }

    const 防守方状态 = 获取武将状态(防守方玩家状态, 实际防守方下标)
    if (!防守方状态 || 防守方状态.气血 <= 0) return

    const 防守方玩家 = 获取玩家信息(战局, 防守方玩家状态)
    const 防守方属性 = 获取武将属性(防守方玩家, 实际防守方下标)
    const 防守方攻击 = 获取武将攻击(防守方玩家, 实际防守方下标)
    const 防守方防御 = 获取武将防御(防守方玩家, 实际防守方下标)
    const 防守方抗物理 = 获取武将抗物理(防守方玩家, 实际防守方下标)
    const 防守方最大气血 = 获取武将最大气血(防守方玩家, 实际防守方下标)

    const 攻击方名称 = 获取武将名称(攻击方玩家, 攻击方下标)
    const 防守方名称 = 获取武将名称(防守方玩家, 实际防守方下标)

    const 对方有效物理抗性 = Math.max(0, Math.min(100, 防守方抗物理) - 攻击方属性.穿透率)

    const 命中率 = 攻击方属性.命中率 - 防守方属性.躲避率
    let 是命中 = 概率判断(命中率)

    let 动画名称
    let 横幅显示
    let 原标准伤害 = 0
    let 原浮动伤害 = 0
    let 最终实际伤害 = 0
    const 忽视天赋效果 = 获取天赋值(攻击方属性, '忽视')
    const 强攻天赋系数 = 获取天赋值(攻击方属性, '强攻')
    const 夺命天赋系数 = 获取天赋值(攻击方属性, '夺命')
    const 合击天赋系数 = 获取天赋值(攻击方属性, '合击')

    if (是命中) {
        if (概率判断(忽视天赋效果)) {
            动画名称 = '普通攻击'
            横幅显示 = '忽视攻击'
            原标准伤害 = 攻击方攻击 * (1 + 强攻天赋系数 / 100)
            原浮动伤害 = 原标准伤害 * 攻击伤害浮动()
            最终实际伤害 = 原浮动伤害
        } else if (概率判断(攻击方属性.暴击率)) {
            动画名称 = '暴击攻击'
            横幅显示 = '暴击攻击'
            原标准伤害 = 攻击方攻击 * (1.5 + 攻击方属性.暴击力 / 100)
            原浮动伤害 = 原标准伤害 * 攻击伤害浮动()
            最终实际伤害 = (原浮动伤害 - 防守方防御) * (1 - 对方有效物理抗性 / 100)
        } else if (概率判断(攻击方属性.致命率)) {
            动画名称 = '致命攻击'
            横幅显示 = '致命攻击'
            原标准伤害 = 攻击方攻击 - 防守方防御 + 防守方最大气血 * 0.2 * (1 + 夺命天赋系数 / 100)
            原浮动伤害 = 原标准伤害 * 攻击伤害浮动()
            最终实际伤害 = 原浮动伤害
        } else if (概率判断(合击天赋系数)) {
            const 合击伙伴 = 获取合击伙伴属性(战局, 攻击方玩家状态, 攻击方下标)
            动画名称 = '普通攻击'
            横幅显示 = `合击攻击(${合击伙伴.名称})`
            原标准伤害 = 攻击方攻击 + 合击伙伴.攻击 - 防守方防御
            原浮动伤害 = 原标准伤害 * 攻击伤害浮动()
            最终实际伤害 = 原浮动伤害 * (1 - 对方有效物理抗性 / 100)
        } else {
            动画名称 = '普通攻击'
            横幅显示 = '普通攻击'
            原标准伤害 = 攻击方攻击 - 防守方防御
            原浮动伤害 = 原标准伤害 * 攻击伤害浮动()
            最终实际伤害 = 原浮动伤害 * (1 - 对方有效物理抗性 / 100)
        }
    } else if (概率判断(忽视天赋效果)) {
        是命中 = true
        动画名称 = '普通攻击'
        横幅显示 = '忽视攻击'
        原标准伤害 = 攻击方攻击 * (1 + 强攻天赋系数 / 100)
        原浮动伤害 = 原标准伤害 * 攻击伤害浮动()
        最终实际伤害 = 原浮动伤害
    } else {
        动画名称 = '攻击未命中'
        横幅显示 = '攻击未命中'
    }

    if (连击次数 > 1) {
        横幅显示 += '(连击)'
    }

    const 战况目标列表 = []

    if (是命中) {
        最终实际伤害 = Math.max(1, Math.round(最终实际伤害))

        受到伤害(战局, 防守方玩家状态, 实际防守方下标, '普通攻击', 最终实际伤害)

        战况目标列表.push({
            玩家名: 防守方玩家.用户名,
            武将下标: 实际防守方下标,
            气血伤害: 最终实际伤害,
            新状态: {气血: 防守方状态.气血},
            buff: 收集武将buff(防守方玩家状态, 实际防守方下标),
        })
    } else {
        战况目标列表.push({
            玩家名: 防守方玩家.用户名,
            武将下标: 实际防守方下标,
        })
    }

    let 简要文本
    if (横幅显示 === '攻击未命中') {
        简要文本 = `${攻击方名称} ${横幅显示} ${防守方名称}`
    } else {
        简要文本 = `${攻击方名称} ${横幅显示} ${防守方名称} 伤害值${最终实际伤害}`
    }

    回合信息.战况事件序列.push({
        玩家名: 攻击方玩家.用户名,
        武将下标: 攻击方下标,
        动画名称: 动画名称,
        横幅显示: 横幅显示,
        目标: 战况目标列表,
        简要文本: 简要文本,
    })

    if (是命中) {
        if (概率判断(防守方属性.反震率)) {
            const 反震伤害 = 最终实际伤害
            受到伤害(战局, 攻击方玩家状态, 攻击方下标, '反震', 反震伤害)
            回合信息.战况事件序列.push({
                玩家名: 防守方玩家.用户名,
                武将下标: 实际防守方下标,
                动画名称: '反震',
                横幅显示: `${防守方名称}反震`,
                目标: [{
                    玩家名: 攻击方玩家.用户名,
                    武将下标: 攻击方下标,
                    气血伤害: 最终实际伤害,
                    新状态: {气血: 攻击方状态.气血},
                    buff: 收集武将buff(攻击方玩家状态, 攻击方下标),
                }],
                简要文本: `${防守方名称} 反震攻击 ${攻击方名称} 伤害值${反震伤害}`,
            })
        } else if (概率判断(防守方属性.反击率)) {
            const 自己有效物理抗性 = Math.max(0, Math.min(100, 攻击方抗物理) - 防守方属性.穿透率)
            const 反击伤害 = Math.max(1, Math.round((防守方攻击 - 攻击方防御) * (1 - 自己有效物理抗性 / 100) * 攻击伤害浮动()))
            受到伤害(战局, 攻击方玩家状态, 攻击方下标, '反击攻击', 反击伤害)
            回合信息.战况事件序列.push({
                玩家名: 防守方玩家.用户名,
                武将下标: 实际防守方下标,
                动画名称: '普通攻击',
                横幅显示: `${防守方名称}反击`,
                目标: [{
                    玩家名: 攻击方玩家.用户名,
                    武将下标: 攻击方下标,
                    气血伤害: 反击伤害,
                    新状态: {气血: 攻击方状态.气血},
                    buff: 收集武将buff(攻击方玩家状态, 攻击方下标),
                }],
                简要文本: `${防守方名称} 反击攻击 ${攻击方名称} 伤害值${反击伤害}`,
            })
        }
    }

    return 是命中
}

/**
 * 处理单个武将的攻击（可能触发连击）
 */
function 处理武将攻击(战局, 回合信息, 攻击方玩家状态, 攻击方下标, 防守方玩家状态, 防守方下标) {
    const 攻击方玩家 = 获取玩家信息(战局, 攻击方玩家状态)
    const 攻击方属性 = 获取武将属性(攻击方玩家, 攻击方下标)
    const 最大连击数 = 攻击方属性.连击数 || 1
    let 连击次数 = 1

    const 第一次命中 = 执行攻击(战局, 回合信息, 攻击方玩家状态, 攻击方下标, 防守方玩家状态, 防守方下标, 连击次数)

    if (!第一次命中) return

    const 攻击方状态 = 获取武将状态(攻击方玩家状态, 攻击方下标)
    if (!攻击方状态 || 攻击方状态.气血 <= 0) return

    const 防守方状态 = 获取武将状态(防守方玩家状态, 防守方下标)
    if (!防守方状态 || 防守方状态.气血 <= 0) return

    while (连击次数 < 最大连击数) {
        if (!概率判断(攻击方属性.连击率)) break

        const 当前攻击方状态 = 获取武将状态(攻击方玩家状态, 攻击方下标)
        if (!当前攻击方状态 || 当前攻击方状态.气血 <= 0) break

        const 当前防守方状态 = 获取武将状态(防守方玩家状态, 防守方下标)
        if (!当前防守方状态 || 当前防守方状态.气血 <= 0) break

        连击次数++
        const 本次命中 = 执行攻击(战局, 回合信息, 攻击方玩家状态, 攻击方下标, 防守方玩家状态, 防守方下标, 连击次数)

        if (!本次命中) break
    }
}

