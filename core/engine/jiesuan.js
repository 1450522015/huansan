function 处理乱buff随机攻击(战局, 回合信息, 攻击方玩家状态, 攻击方下标) {
    const 所有存活武将 = 获取所有存活武将列表(战局)
    if (所有存活武将.length === 0) return

    const 随机目标 = 所有存活武将[Math.floor(Math.random() * 所有存活武将.length)]
    const 目标下标 = 随机目标.武将下标

    const 防守方玩家状态 = 随机目标.是红方 ? 战局.红方.状态 : 战局.黑方.状态
    const 防守方状态 = 获取武将状态(防守方玩家状态, 目标下标)
    if (!防守方状态 || 防守方状态.气血 <= 0) return

    处理武将攻击(战局, 回合信息, 攻击方玩家状态, 攻击方下标, 防守方玩家状态, 目标下标)
}

export function 战局结算(战局, 红方出招, 黑方出招) {
    const 当前回合数 = 战局.战局描述.当前回合
    const 当前回合信息 = 战局.回合信息.find(r => r.回合数 === 当前回合数)

    if (!当前回合信息) return 战局

    当前回合信息.红方出招 = 红方出招
    当前回合信息.黑方出招 = 黑方出招

    if (当前回合数 > 1) {
        处理回合前置事件(战局, 当前回合信息)
    }

    function 获取所有存活武将() {
        const 结果 = []
        if (战局.红方.状态.主将.气血 > 0) {
            结果.push({玩家状态: 战局.红方.状态, 下标: -1})
        }
        for (const 副将 of 战局.红方.状态.副将列表) {
            if (副将 && 副将.气血 > 0) {
                结果.push({玩家状态: 战局.红方.状态, 下标: 副将.武将下标})
            }
        }
        if (战局.黑方.状态.主将.气血 > 0) {
            结果.push({玩家状态: 战局.黑方.状态, 下标: -1})
        }
        for (const 副将 of 战局.黑方.状态.副将列表) {
            if (副将 && 副将.气血 > 0) {
                结果.push({玩家状态: 战局.黑方.状态, 下标: 副将.武将下标})
            }
        }
        return 结果
    }

    const 已行动 = new Set()
    const 武将key = (w) => `${w.玩家状态.是红方 ? '红' : '黑'}_${w.下标}`

    while (true) {
        const 所有存活武将 = 获取所有存活武将()
        const 未行动武将 = 所有存活武将.filter(w => !已行动.has(武将key(w)))
        if (未行动武将.length === 0) break

        未行动武将.sort((a, b) => {
            const a状态 = 获取武将状态(a.玩家状态, a.下标)
            const b状态 = 获取武将状态(b.玩家状态, b.下标)
            return a状态.速度排名 - b状态.速度排名
        })

        const 当前武将 = 未行动武将[0]
        已行动.add(武将key(当前武将))

        const 出招 = (当前武将.玩家状态.是红方 ? 当前回合信息.红方出招 : 当前回合信息.黑方出招)
            .find(z => z.出招方武将下标 === 当前武将.下标)

        const 有封buff = 检查武将拥有buff(当前武将.玩家状态, 当前武将.下标, '封')
        const 有乱buff = 检查武将拥有buff(当前武将.玩家状态, 当前武将.下标, '乱')
        const 有围buff = 检查武将拥有buff(当前武将.玩家状态, 当前武将.下标, '围')

        if (有封buff) {
            continue;
        } else if (有乱buff) {
            处理乱buff随机攻击(战局, 当前回合信息, 当前武将.玩家状态, 当前武将.下标)
        } else if (!出招) {
            if (有围buff) {
                continue
            }
            const 防守方玩家状态 = 当前武将.玩家状态.是红方 ? 战局.黑方.状态 : 战局.红方.状态
            const 目标下标 = 获取最高速存活武将下标(防守方玩家状态)
            const 防守方状态 = 获取武将状态(防守方玩家状态, 目标下标)
            if (!防守方状态 || 防守方状态.气血 <= 0) continue
            处理武将攻击(战局, 当前回合信息, 当前武将.玩家状态, 当前武将.下标, 防守方玩家状态, 目标下标)
        } else if (出招.操作 === '攻击') {
            if (有围buff) {
                continue
            }
            const 目标下标 = 出招.接招方武将下标
            const 防守方玩家状态 = 当前武将.玩家状态.是红方 ? 战局.黑方.状态 : 战局.红方.状态
            const 原防守方状态 = 获取武将状态(防守方玩家状态, 目标下标)

            const 实际目标下标 = (!原防守方状态 || 原防守方状态.气血 <= 0)
                ? 获取最高速存活武将下标(防守方玩家状态)
                : 目标下标
            const 防守方状态 = 获取武将状态(防守方玩家状态, 实际目标下标)

            if (!防守方状态 || 防守方状态.气血 <= 0) continue

            处理武将攻击(战局, 当前回合信息, 当前武将.玩家状态, 当前武将.下标, 防守方玩家状态, 实际目标下标)
        } else if (出招.操作 === '防御') {
            处理防御(战局, 当前回合信息, 当前武将.玩家状态, 当前武将.下标)
        } else if (出招.操作 === '物品') {
            const 接招方玩家状态 = 当前武将.玩家状态
            const 实际接招方下标 = 出招.接招方武将下标
            处理物品(战局, 当前回合信息, 当前武将.玩家状态, 当前武将.下标, 接招方玩家状态, 实际接招方下标, 出招.物品)
        } else if (出招.操作 === '技能') {
            if (有围buff) {
                continue
            }
            处理技能(战局, 当前回合信息, 当前武将, 出招)
        } else if (出招.操作 === '招将') {
            处理招将(战局, 当前回合信息, 当前武将.玩家状态, 当前武将.下标, 出招.招将)
        }

        const 红方存活 = 获取存活武将列表(战局.红方.状态).length > 0
        const 黑方存活 = 获取存活武将列表(战局.黑方.状态).length > 0
        if (!红方存活 || !黑方存活) {
            战局.战局描述.状态 = '已结束'
            if (!红方存活 && !黑方存活) {
                战局.战局描述.战胜方玩家名称 = null
                战局.战局描述.结束原因 = '平局'
            } else {
                战局.战局描述.战胜方玩家名称 = 红方存活 ? 战局.战局描述.红方用户名 : 战局.战局描述.黑方用户名
                战局.战局描述.结束原因 = `${战局.战局描述.战胜方玩家名称} 胜利`
            }
            return 战局
        }
    }

    处理回合后置事件(战局, 当前回合信息)

    战局.战局描述.当前回合++
    战局.回合信息.push({
        回合数: 战局.战局描述.当前回合,
        红方出招: [],
        黑方出招: [],
        回合初状态: {
            红方: JSON.parse(JSON.stringify(战局.红方.状态)),
            黑方: JSON.parse(JSON.stringify(战局.黑方.状态)),
        },
        战况事件序列: [],
    })

    return 战局
}
