function 毒发(战局, 回合信息) {
    const 当前回合数 = 回合信息.回合数
    let 所有存活武将列表 = 获取所有存活武将列表(战局)
    const 毒发目标数组 = []
    for (let 武将状态 of 所有存活武将列表) {
        let 玩家状态 = 武将状态.是红方 ? 战局.红方.状态 : 战局.黑方.状态
        const 有毒buff = 武将状态.buff && 武将状态.buff.some(b => b.名称 === '毒')
        let 当前回合毒伤害 = 0
        for (let i = 武将状态.buff.length - 1; i >= 0; i--) {
            const b = 武将状态.buff[i]
            if (b.名称 !== '毒') continue
            const 已持续回合 = 当前回合数 - b.开始回合数
            if (b.巫蛊极毒衰减模式 === '第一回合的50%') {
                当前回合毒伤害 += Math.max(Math.round(b.原效果 * 0.5), 1)
            } else if (b.巫蛊极毒衰减模式 === '上一回合的75%') {
                当前回合毒伤害 += Math.max(Math.round(b.原效果 * Math.pow(0.75, 已持续回合)), 1)
            }
            if (已持续回合 >= b.总回合数) {
                武将状态.buff.splice(i, 1)
            }
        }
        if (有毒buff) {
            受到伤害(战局, 玩家状态, 武将状态.武将下标, '毒发', 当前回合毒伤害)
            毒发目标数组.push({
                玩家名: 武将状态.是红方 ? 战局.红方.用户名 : 战局.黑方.用户名,
                武将下标: 武将状态.武将下标,
                气血伤害: 当前回合毒伤害,
                新状态: {气血: 武将状态.气血},
                buff: 收集武将buff(玩家状态, 武将状态.武将下标),
            })
        }
    }
    if (毒发目标数组.length > 0) {
        回合信息.战况事件序列.push({
            动画名称: '毒发',
            横幅显示: `毒发`,
            目标: 毒发目标数组,
            简要文本: `毒发`,
        })
    }
}

function 爆炸(战局, 回合信息) {
    const 当前回合数 = 回合信息.回合数
    let 所有存活武将列表 = 获取所有存活武将列表(战局)

    for (let 武将状态 of 所有存活武将列表) {
        const 毁buff = 武将状态.buff.find(b => b.名称 === '毁')
        if (!毁buff) continue

        const 生效回合 = 毁buff.开始回合数 + 3
        if (当前回合数 !== 生效回合) continue

        const 玩家状态 = 武将状态.是红方 ? 战局.红方.状态 : 战局.黑方.状态
        const 玩家信息 = 获取玩家信息(战局, 玩家状态)

        const 目标数组 = []

        const 雷属性面板伤害 = 毁buff.原效果 || 0
        const 火属性面板伤害 = 毁buff.毁天灭地溅射伤害 || 0

        const 抗性 = 获取武将抗法术(玩家信息, 武将状态.武将下标, '抗落雷')
        const 有效抗性 = Math.max(0, Math.min(100, Math.min(100, 抗性)))
        let 实际雷伤害 = Math.round(雷属性面板伤害 * (1 - 有效抗性 / 100))
        if (实际雷伤害 < 1) 实际雷伤害 = 1

        受到伤害(战局, 玩家状态, 武将状态.武将下标, '爆炸', 实际雷伤害)

        目标数组.push({
            玩家名: 玩家信息.用户名,
            武将下标: 武将状态.武将下标,
            气血伤害: 实际雷伤害,
            新状态: {气血: 武将状态.气血},
            buff: 收集武将buff(玩家信息.状态, 武将状态.武将下标),
        })

        let 存活武将列表 = 获取多目标武将列表(玩家状态, 武将状态.武将下标, 4)
        for (let 其他武将 of 存活武将列表) {
            if (其他武将 === 武将状态) continue
            if (其他武将.气血 <= 0) continue

            const 抗性 = 获取武将抗法术(玩家信息, 其他武将.武将下标, '抗妖火')
            const 有效抗性 = Math.max(0, Math.min(100, Math.min(100, 抗性)))
            let 实际火伤害 = Math.round(火属性面板伤害 * (1 - 有效抗性 / 100))
            if (实际火伤害 < 1) 实际火伤害 = 1

            受到伤害(战局, 玩家状态, 其他武将.武将下标, '爆炸', 实际火伤害)

            目标数组.push({
                玩家名: 玩家信息.用户名,
                武将下标: 其他武将.武将下标,
                气血伤害: 实际火伤害,
                新状态: {气血: 其他武将.气血},
                buff: 收集武将buff(玩家信息.状态, 其他武将.武将下标),
            })
        }

        const buffIndex = 武将状态.buff.indexOf(毁buff)
        if (buffIndex !== -1) {
            武将状态.buff.splice(buffIndex, 1)
        }

        回合信息.战况事件序列.push({
            动画名称: '爆炸',
            横幅显示: `爆炸`,
            目标: 目标数组,
            简要文本: `毁天灭地爆炸`,
        })
    }
}

function 围乱封二次判定(战局, 回合信息) {
    const 当前回合数 = 回合信息.回合数
    const 所有存活武将列表 = 获取所有存活武将列表(战局)
    for (const 武将状态 of 所有存活武将列表) {
        if (!武将状态.buff) continue
        for (const buff of 武将状态.buff) {
            if (buff.名称 !== '围' && buff.名称 !== '乱' && buff.名称 !== '封') {
                continue
            }
            if (当前回合数 !== buff.开始回合数 + 1) {
                continue
            }
            let 玩家状态 = 武将状态.是红方 ? 战局.红方.状态 : 战局.黑方.状态
            const 玩家信息 = 获取玩家信息(战局, 玩家状态)
            const 抗性字段 = buff.名称 === '围' ? '抗围困' : buff.名称 === '乱' ? '抗扰乱' : '抗封锁'
            const 目标抗性 = 获取武将抗法术(玩家信息, 武将状态.武将下标, 抗性字段)
            const 实际成功率 = buff.原成功率 - 目标抗性
            if (!概率判断(实际成功率)) {
                移除武将buff(玩家状态, 武将状态.武将下标, buff.名称)
            }
        }
    }
}

function buff失效(战局, 回合信息) {
    const 当前回合数 = 回合信息.回合数
    const 所有存活武将列表 = 获取所有存活武将列表(战局)
    for (const 武将状态 of 所有存活武将列表) {
        if (!武将状态.buff) continue
        const 剩余buffs = []
        for (const buff of 武将状态.buff) {
            if (当前回合数 >= buff.开始回合数 + buff.总回合数) {
                continue
            }
            剩余buffs.push(buff)
        }
        武将状态.buff = 剩余buffs
    }
}

