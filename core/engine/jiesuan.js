function 处理回合后置事件(战局, 回合信息) {
    围乱封二次判定(战局, 回合信息)
    buff失效(战局, 回合信息)
    let 所有存活武将列表 = 获取所有存活武将列表(战局)
    for (let 武将状态 of 所有存活武将列表) {
        处理无双开启(战局, 回合信息, 武将状态.是红方 ? 战局.红方.状态 : 战局.黑方.状态, 武将状态.武将下标)
    }
    for (let 武将状态 of 所有存活武将列表) {
        处理无双关闭(战局, 回合信息, 武将状态.是红方 ? 战局.红方.状态 : 战局.黑方.状态, 武将状态.武将下标)
    }
    重新计算速度排名(战局)
}

