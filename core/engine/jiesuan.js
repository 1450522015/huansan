function 处理招将(战局, 回合信息, 玩家状态, 出招方下标, 招将下标) {
    if (出招方下标 !== -1) return

    const 武将状态 = 获取武将状态(玩家状态, 出招方下标)
    if (!武将状态 || 武将状态.气血 <= 0) return

    const 玩家信息 = 获取玩家信息(战局, 玩家状态)
    const 配置 = 玩家信息.配置
    const 属性 = 玩家信息.属性

    const 副将配置 = 配置.副将列表[招将下标]
    const 副将属性 = 属性.副将列表[招将下标]
    if (!副将配置 || !副将属性) return

    if (玩家状态.副将死亡列表.includes(招将下标)) return

    const 第一个空位 = 玩家状态.副将列表.findIndex(s => s === null)
    if (第一个空位 === -1) return

    let 文人数量 = 0
    if (武将状态.角色分类[1] === '文') 文人数量++
    for (const 副将 of 玩家状态.副将列表) {
        if (副将 && 副将.角色分类[1] === '文') 文人数量++
    }
    if (副将属性.角色分类[1] === '文' && 文人数量 >= 2) return

    const 新副将状态 = {
        是红方: 玩家状态.是红方,
        武将下标: 招将下标,
        角色分类: 副将属性.角色分类,
        气血: 副将属性.气血,
        精力: 副将属性.精力,
        速度排名: 0,
        buff: [],
        无双: {
            无双几率: (副将配置.无双等级 || 0) * 0.5,
            是否开启: false,
            开启回合数: 0,
            关闭回合数: 0,
            本局开启次数: 0,
        }
    }

    玩家状态.副将列表[第一个空位] = 新副将状态

    const 武将名称 = 获取武将名称(玩家信息, 招将下标)
    const 主将名称 = 获取武将名称(玩家信息, -1)

    回合信息.战况事件序列.push({
        玩家名: 玩家信息.用户名,
        武将下标: 出招方下标,
        动画名称: '招将',
        横幅显示: `${主将名称}招将${武将名称}`,
        目标: [{
            玩家名: 玩家信息.用户名,
            武将下标: 招将下标,
            新状态: {
                气血: 新副将状态.气血,
                精力: 新副将状态.精力,
            },
        }],
        简要文本: `${主将名称} 招将 ${武将名称}`,
    })
}

