function 处理物品(战局, 回合信息, 出招方玩家状态, 出招方下标, 接招方玩家状态, 接招方下标, 物品名称) {
    const 出招方状态 = 获取武将状态(出招方玩家状态, 出招方下标)
    if (!出招方状态 || 出招方状态.气血 <= 0) return

    let 实际接招方下标 = 接招方下标
    let 实际接招方状态 = 获取武将状态(接招方玩家状态, 接招方下标)

    if (!实际接招方状态 || 实际接招方状态.气血 <= 0) {
        if (接招方下标 !== -1) {
            实际接招方下标 = 获取最高速存活武将下标(接招方玩家状态, true)
            实际接招方状态 = 获取武将状态(接招方玩家状态, 实际接招方下标)
        }
    }

    const 出招方玩家 = 获取玩家信息(战局, 出招方玩家状态)
    const 接招方玩家 = 获取玩家信息(战局, 接招方玩家状态)
    const 出招方名称 = 获取武将名称(出招方玩家, 出招方下标)
    const 接招方名称 = 获取武将名称(接招方玩家, 实际接招方下标)

    let 事件 = {
        玩家名: 出招方玩家.用户名,
        武将下标: 出招方下标,
    }
    let 目标事件 = {
        玩家名: 接招方玩家.用户名,
        武将下标: 实际接招方下标,
    }
    if (物品名称 === '九转丹') {
        const 最大气血 = 获取武将最大气血(接招方玩家, 实际接招方下标)
        实际接招方状态.气血 = 最大气血
        目标事件.气血回复 = 最大气血
        目标事件.新状态 = {气血: 最大气血}
        事件.动画名称 = '九转丹'
        事件.横幅显示 = `${出招方名称}使用九转丹`
        事件.简要文本 = `${出招方名称} 使用九转丹 ${接招方名称} 气血回复至${最大气血}`
    } else if (物品名称 === '龙涎露') {
        const 最大精力 = 获取武将最大精力(接招方玩家, 实际接招方下标)
        实际接招方状态.精力 = 最大精力
        目标事件.精力回复 = 最大精力
        目标事件.新状态 = {精力: 最大精力}
        事件.动画名称 = '龙涎露'
        事件.横幅显示 = `${出招方名称}使用龙涎露`
        事件.简要文本 = `${出招方名称} 使用龙涎露 ${接招方名称} 精力回复至${最大精力}`
    } else {
        return
    }
    事件.目标 = [目标事件]
    回合信息.战况事件序列.push(事件)
}

function 处理无双开启(战局, 回合信息, 玩家状态, 武将下标) {
    const 武将状态 = 获取武将状态(玩家状态, 武将下标)
    if (!武将状态 || !武将状态.无双) return

    const 无双 = 武将状态.无双
    if (无双.是否开启 || 无双.本局开启次数 >= 3) return
    if (!概率判断(无双.无双几率)) return

    const 玩家信息 = 获取玩家信息(战局, 玩家状态)
    const 副将属性 = 玩家信息.属性.副将列表[武将下标]
    const 无双属性 = 副将属性?.无双属性
    if (!无双属性) return

    武将状态.气血 = Math.round(武将状态.气血 * (无双属性.气血 / 副将属性.气血))
    武将状态.精力 = Math.round(武将状态.精力 * (无双属性.精力 / 副将属性.精力))

    无双.是否开启 = true
    无双.开启回合数 = 回合信息.回合数
    无双.本局开启次数++

    const 武将名称 = 获取武将名称(玩家信息, 武将下标)
    const 玩家名 = 玩家信息.用户名

    回合信息.战况事件序列.push({
        玩家名: 玩家名,
        武将下标: 武将下标,
        动画名称: '无双开启',
        横幅显示: `${武将名称}开启无双`,
        新状态: {
            气血: 武将状态.气血,
            精力: 武将状态.精力,
            最大气血: 无双属性.气血,
            最大精力: 无双属性.精力,
        },
        简要文本: `${武将名称}开启无双`,
    })
}

