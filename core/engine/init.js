import {获取武将速度, 获取玩家信息, 重新计算速度排名} from "./common.js";
import {玩家配置转玩家属性} from "../attr.js";

/**
 * 初始化武将状态
 * @param {boolean} 是红方
 * @param {number} 武将下标 - 主将为 -1，副将为副将列表中的下标
 * @param {object} 武将配置
 * @param {object} 武将属性
 * @returns {object} 武将状态
 */
function 初始化武将状态(是红方, 武将下标, 武将配置, 武将属性) {
    return {
        是红方: 是红方,
        武将下标: 武将下标,
        角色分类: 武将属性.角色分类,
        气血: 武将属性.气血,
        精力: 武将属性.精力,
        速度排名: 0,
        buff: []
    }
}

/**
 * 初始化玩家状态（不保存到玩家信息，而是由调用方使用）
 * @param {object} 玩家信息
 * @param {boolean} 是红方
 * @returns {object} 玩家状态
 */
function 初始化玩家状态(玩家信息, 是红方) {
    const 配置 = 玩家信息.配置
    const 属性 = 玩家信息.属性
    const 上阵顺序 = 配置.副将上阵顺序

    // 初始化主将状态（下标 = -1）
    const 主将状态 = 初始化武将状态(是红方, -1, 配置.主将, 属性.主将)

    // 根据副将上阵顺序生成副将状态列表
    const 副将状态列表 = []
    for (let i = 0; i < 上阵顺序.length; i++) {
        const 下标 = 上阵顺序[i]
        const 副将配置 = 配置.副将列表[下标]
        const 副将属性 = 属性.副将列表[下标]
        let 副将状态 = 初始化武将状态(是红方, 下标, 副将配置, 副将属性);
        副将状态.无双 = {
            无双几率: (副将配置.无双等级 || 0) * 0.5,
            是否开启: false,
            开启回合数: 0,
            关闭回合数: 0,
            本局开启次数: 0,
        }
        副将状态列表.push(副将状态)
    }

    return {
        是红方: 是红方,
        主将: 主将状态,
        副将列表: 副将状态列表,
        副将死亡列表: []
    }
}

/**
 * @returns {import('./types').战局}
 */
export function 战局初始化(id, 红方用户名, 红方配置, 黑方用户名, 黑方配置) {
    const 红方属性 = 玩家配置转玩家属性(红方配置)
    const 黑方属性 = 玩家配置转玩家属性(黑方配置)

    const 战局 = {
        战局描述: {
            id: id,
            红方用户名: 红方用户名,
            黑方用户名: 黑方用户名,
            当前回合: 1,
            状态: '战局中',
            战胜方玩家名称: null,
        },
        红方: {
            用户名: 红方用户名,
            配置: 红方配置,
            属性: 红方属性,
            状态: null,
        },
        黑方: {
            用户名: 黑方用户名,
            配置: 黑方配置,
            属性: 黑方属性,
            状态: null,
        },
    }

    战局.红方.状态 = 初始化玩家状态(战局.红方, true)
    战局.黑方.状态 = 初始化玩家状态(战局.黑方, false)

    重新计算速度排名(战局)

    // 回合信息中保存状态快照（用于回放等用途）
    战局.回合信息 = [
        {
            回合数: 1,
            红方出招: [],
            黑方出招: [],
            回合初状态: {
                红方: JSON.parse(JSON.stringify(战局.红方.状态)),
                黑方: JSON.parse(JSON.stringify(战局.黑方.状态)),
            },
            战况事件序列: [],
        }
    ]

    return 战局
}
